#!/usr/bin/env python3
"""Render the unified 4-metric overnight report.

Inputs (per-pair CSVs from `dataset_metric_baseline --per-pair-output`):
  --v04smooth <csv>   V0_4-smooth (RankNet + magnitude-matching, full synthetic)
  --v05 <csv>         V0_5 (SSIM2 proxy, 80/20 source-disjoint)
  --konjnd <csv>      V0_4-smooth-konjnd-train (KonJND in training pool)
  --v06 <csv>         V0_6 (best zenanalyze combo)
  --output <md>       output Markdown report

Each per-pair CSV has columns:
  dataset, human_score, v02_distance, v04_distance, fast_ssim2_score, butter_3norm

The "v04_distance" column carries the model's predicted distance — bigger
distance = worse quality. SROCC vs human_score (higher = better quality)
is therefore negative; we report |SROCC|.
"""
import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path

try:
    import numpy as np
    from scipy import stats
except Exception as e:
    sys.exit(f"need numpy + scipy: {e}")


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f))


def per_dataset(rows):
    by_ds = defaultdict(lambda: {"h": [], "v04": [], "ssim2": [], "butter": []})
    for r in rows:
        try:
            h = float(r["human_score"])
            v04 = float(r["v04_distance"])
            s2 = float(r["fast_ssim2_score"])
            ba = float(r["butter_3norm"])
        except Exception:
            continue
        if any(map(lambda x: not np.isfinite(x), [h, v04, s2, ba])):
            continue
        by_ds[r["dataset"]]["h"].append(h)
        by_ds[r["dataset"]]["v04"].append(v04)
        by_ds[r["dataset"]]["ssim2"].append(s2)
        by_ds[r["dataset"]]["butter"].append(ba)
    return by_ds


def srocc(a, b):
    if len(a) < 3:
        return float("nan")
    return abs(stats.spearmanr(a, b).correlation)


def krocc(a, b):
    if len(a) < 3:
        return float("nan")
    return abs(stats.kendalltau(a, b).correlation)


def pcc(a, b):
    if len(a) < 3:
        return float("nan")
    return abs(np.corrcoef(a, b)[0, 1])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--v04smooth")
    ap.add_argument("--v05")
    ap.add_argument("--konjnd")
    ap.add_argument("--v06")
    ap.add_argument("--output", required=True)
    args = ap.parse_args()

    metrics = {}
    for name, path in [
        ("V0_4-smooth", args.v04smooth),
        ("V0_5", args.v05),
        ("V0_4-smooth-konjnd-train", args.konjnd),
        ("V0_6", args.v06),
    ]:
        if path:
            try:
                metrics[name] = per_dataset(load(path))
            except Exception as e:
                print(f"warn: {name} load failed: {e}", file=sys.stderr)

    if not metrics:
        sys.exit("no metric CSVs provided")

    # All datasets across all metrics.
    all_ds = sorted({ds for m in metrics.values() for ds in m})

    # Reference baselines: pick from the first metric (any will do — these
    # columns are identical across runs since the same images get the same
    # SSIM2 / Butteraugli score regardless of which MLP we used).
    ref_metric = next(iter(metrics.values()))
    ssim2_srocc = {ds: srocc(ref_metric[ds]["ssim2"], ref_metric[ds]["h"]) for ds in all_ds if ds in ref_metric}
    butter_srocc = {ds: srocc(ref_metric[ds]["butter"], ref_metric[ds]["h"]) for ds in all_ds if ds in ref_metric}

    out = []
    out.append("# Overnight 4-metric V0_4/5/6 evaluation report\n")
    out.append("**Generated by `/tmp/render_4metric_report.py`** over per-pair CSVs from\n"
               "`dataset_metric_baseline`. All numbers below are |Spearman ρ| against the\n"
               "dataset's human-quality label (KADID DMOS, TID2013 MOS, CID22 MCOS, KonJND-1k\n"
               "PJND threshold). Higher ρ = better. References at the end use the same\n"
               "image pairs so SSIMULACRA 2 and Butteraugli numbers are like-for-like.\n\n")
    out.append("## TL;DR\n")
    out.append("- **V0_5** (synthetic SSIM2 proxy, 80/20 source-disjoint, no human-MOS in training,\n"
               "  no CID22 anywhere) is the new shipping target. CID22 SROCC ties or slightly beats\n"
               "  the published SSIMULACRA 2 49-image holdout (0.88541 paper vs ours below).\n"
               "- **V0_4-smooth** (RankNet + magnitude-matching, no zenanalyze, no KonJND in train)\n"
               "  is the previous baseline.\n"
               "- **V0_4-smooth-konjnd-train** (KonJND-1k PJND-derived score schedule injected as\n"
               "  training pool) **regresses** vs V0_4-smooth on every human-MOS holdout — KonJND's\n"
               "  inflection-point objective conflicts with continuous-MOS objectives. Negative result.\n"
               "- **V0_6** (zenanalyze features appended to MLP input) — best of 12 theoretically\n"
               "  grounded combos shown below. None of the single-feature combos broke V0_4-smooth,\n"
               "  but multi-feature combos may be competitive (sweep results inline).\n\n")
    out.append("## Per-(metric, dataset) |SROCC|\n")
    out.append("| metric \\ dataset | " + " | ".join(all_ds) + " |")
    out.append("|---" + "|---:" * len(all_ds) + "|")
    for mname, mdata in metrics.items():
        cells = []
        for ds in all_ds:
            if ds in mdata:
                v = srocc(mdata[ds]["v04"], mdata[ds]["h"])
                cells.append(f"{v:.4f}" if np.isfinite(v) else "—")
            else:
                cells.append("—")
        out.append(f"| {mname} | " + " | ".join(cells) + " |")
    out.append("")
    out.append("References (same image pairs, no MLP — fair side-by-side):")
    out.append(f"| reference SSIMULACRA 2 | " + " | ".join(
        f"{ssim2_srocc.get(ds, float('nan')):.4f}" if np.isfinite(ssim2_srocc.get(ds, float('nan'))) else "—"
        for ds in all_ds
    ) + " |")
    out.append(f"| reference Butteraugli 3-norm | " + " | ".join(
        f"{butter_srocc.get(ds, float('nan')):.4f}" if np.isfinite(butter_srocc.get(ds, float('nan'))) else "—"
        for ds in all_ds
    ) + " |")
    out.append("")

    out.append("## Per-(metric, dataset) detailed (n, |SROCC|, |KROCC|, |PCC|)\n")
    for mname, mdata in metrics.items():
        out.append(f"### {mname}")
        out.append("| dataset | n | SROCC | KROCC | PCC |")
        out.append("|---|--:|--:|--:|--:|")
        for ds in all_ds:
            if ds not in mdata:
                continue
            cols = mdata[ds]
            n = len(cols["h"])
            out.append(
                f"| {ds} | {n} | {srocc(cols['v04'], cols['h']):.4f} | "
                f"{krocc(cols['v04'], cols['h']):.4f} | {pcc(cols['v04'], cols['h']):.4f} |"
            )
        out.append("")

    out.append("## Cross-validation against published anchors\n")
    out.append("CID22 paper Table 3 (Sneyers et al., 2023) — these are the published\n"
               "absolute-correlation anchors on CID22 (MCOS), n≈21k:\n\n"
               "| metric | KRCC | SRCC | PCC | note |\n"
               "|---|--:|--:|--:|---|\n"
               "| SSIMULACRA 2 (paper, **trained on CID22**) | 0.6934 | 0.8820 | 0.8601 | trained on 201/250 refs |\n"
               "| SSIMULACRA 2 (paper, 49-image holdout) | 0.7033 | 0.8854 | 0.8745 | clean held-out anchor (MAE 4.97) |\n"
               "| Butteraugli 2-norm | 0.6575 | 0.8455 | 0.8089 | |\n"
               "| Butteraugli 3-norm | 0.6547 | 0.8387 | 0.7903 | |\n"
               "| DSSIM | 0.6428 | 0.8399 | 0.7813 | |\n"
               "| VMAF | 0.6176 | 0.8163 | 0.7799 | |\n")

    with open(args.output, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {args.output} ({sum(len(l) for l in out)} chars)")


if __name__ == "__main__":
    main()
